namespace ParentalGuard.Agent;

/// <summary>
/// Entry point for the Agent (M2). It's now a WinForms application instead of a console app,
/// so it can own a system-tray icon and show overlay windows. There is no main window — the
/// app's "life" is an <see cref="AgentApplicationContext"/>, which runs the message loop while
/// the tray icon stays resident.
///
/// WinForms requires the UI thread to be single-threaded apartment (STA), so we keep an explicit
/// [STAThread] Main rather than top-level statements.
/// </summary>
internal static class Program
{
    [STAThread]
    private static void Main()
    {
        // High-DPI + default font setup generated by the WinForms SDK.
        ApplicationConfiguration.Initialize();

        // Run the tray context. Application.Run pumps the Windows message loop so the tray
        // icon, balloons and overlays all work; it returns only when the context exits.
        Application.Run(new AgentApplicationContext());
    }
}
